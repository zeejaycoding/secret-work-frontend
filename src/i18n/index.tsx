type TFunction = (
  key: string,
  vars?: Record<string, string | number>
) => string;

interface LanguageContextValue {
  locale: Locale;
  languageName: string;
  isRTL: boolean;
  t: TFunction;
  setLanguage: (name: string) => void;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("en");

  useEffect(() => {
    let active = true;
    loadPreferences()
      .then((prefs) => {
        if (!active) return;
        const code = NAME_TO_LOCALE[prefs.language] || "en";
        setLocale(code);
      })
      .catch(() => {});
    return () => {
      active = false;
    };
  }, []);

  const setLanguage = useCallback((name: string) => {
    const code = NAME_TO_LOCALE[name] || "en";
    setLocale(code);
    savePreferences({ language: name });
  }, []);

  const t: TFunction = useCallback(
    (key, vars) => {
      let str = translations[locale][key] ?? "";
      if (!str) str = translations.en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
        }
      }
      return str;
    },
    [locale]
  );

  const isRTL = RTL_LOCALES.includes(locale);

  return (
    <LanguageContext.Provider
      value={{
        locale,
        languageName: LANGUAGE_NAMES[locale],
        isRTL,
        t,
        setLanguage,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return ctx;
}
